/* 頂點類別 */
class Vertex {
    val;
    constructor(val) {
        this.val = val;
    }

    /* 傳入數值陣列 vals，回傳頂點陣列 vets */
    static valsToVets(vals) {
        const vets = [];
        for (let i = 0; i < vals.length; i++) {
            vets[i] = new Vertex(vals[i]);
        }
        return vets;
    }

    /* 傳入頂點陣列 vets，回傳數值陣列 vals */
    static vetsToVals(vets) {
        const vals = [];
        for (const vet of vets) {
            vals.push(vet.val);
        }
        return vals;
    }
}

module.exports = {
    Vertex,
};
