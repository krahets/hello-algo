package chapter_sorting

import (
	"fmt"
	"testing"
)

// Quicksort
func TestQuickSort(t *testing.T) {
	q := quickSort{}
	nums := []int{4, 1, 3, 1, 5, 2}
	q.quickSort(nums, 0, len(nums)-1)
	fmt.Println("After quicksort, nums = ", nums)
}

