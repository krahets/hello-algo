#pragma once

#include <vector>

using namespace std;

/* Vertex class */
struct Vertex {
    int val;
    Vertex(int x) : val(x) {
    }
};

/* Given the list of values vals, return the list of vertices vets */
vector<Vertex *> valsToVets(vector<int> vals) {
    vector<Vertex *> vets;
    for (int val : vals) {
        vets.push_back(new Vertex(val));
    }
    return vets;
}

/* Given the list of vertices vets, return the list of values vals */
vector<int> vetsToVals(vector<Vertex *> vets) {
    vector<int> vals;
    for (Vertex *vet : vets) {
        vals.push_back(vet->val);
    }
    return vals;
}
